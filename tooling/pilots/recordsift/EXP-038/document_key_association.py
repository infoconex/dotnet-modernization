#!/usr/bin/env python3
"""EXP-038: private document-to-native-stream key equality and checksum structure audit.

Only trusted locally compiled native PDBs. Never output the full document URLs,
native named keys, complete paths, source bytes, or actual digest hex.
A private base64 URL file is generated by the bounded managed reader, consumed
in runner.temp and deleted after processing; no such file is uploaded.
"""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import struct
import sys
import uuid

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "tooling" / "validators"))
from native_windows_pdb_sourcelink import read_msf, parse_named_streams, read_pe_codeview

VARIANTS = ("explicit-sha256", "implicit-checksum", "deterministic-only",
            "deterministic-pathmap", "deterministic-pathmap-sourcelink")
OWNED = ("CharacterLimitedTextReader.cs", "CsvRecordReaderAdapter.cs",
         "CsvStreamImporterAdapter.cs", "MalformedCsvException.cs")
GUID_SHA256 = uuid.UUID("8829d00f-11b8-4213-878b-770e8597ac16")
GUID_SHA1 = uuid.UUID("ff1816ec-aa5e-4d10-87f7-6f4963833460")
ALGORITHMS = {GUID_SHA256: "sha256", GUID_SHA1: "sha1"}

def private_urls(file):
    result = {}
    if file.stat().st_size > 128 * 1024:
        raise ValueError("Private URL manifest exceeds size bound")
    for line in file.read_text(encoding="utf-8").splitlines():
        fields = line.split("\t")
        if len(fields) != 2 or not fields[0] or fields[0] in result:
            raise ValueError("Malformed or duplicate reader document manifest")
        url = base64.b64decode(fields[1], validate=True).decode("utf-8", "strict")
        if len(url) > 4096 or not url or not url.lower().endswith(fields[0].lower()):
            raise ValueError("Invalid URL/name correspondence")
        result[fields[0]] = url
    if not result:
        raise ValueError("Empty private URL inventory")
    return result

def stream_record(data):
    """Decode the actual Roslyn injected native source-info stream layout.

    Four little-endian GUIDs: language/vendor/type/checksum algorithm, then
    signed checksum-size and source-size, then raw checksum and source bytes.
    Fail closed on malformed sizes; do not interpret arbitrary stream fragments.
    """
    if data is None or not (72 <= len(data) <= 2 * 1024 * 1024):
        return None
    try:
        alg = uuid.UUID(bytes_le=data[48:64])
        n, source_n = struct.unpack_from("<ii", data, 64)
    except (ValueError, struct.error):
        return None
    if alg not in ALGORITHMS or n not in (20, 32) or source_n < 0 or 72+n+source_n != len(data):
        return None
    if len(data[72:72+n]) != n or n != (20 if alg == GUID_SHA1 else 32):
        return None
    return {"algorithm": ALGORITHMS[alg], "digest": data[72:72+n]}

def norm_slashes(s):
    return s.replace("\\", "/").casefold()

def classify(expected, actual):
    return {
        "exact_key": expected == actual,
        "case_insensitive_key": expected.casefold() == actual.casefold(),
        "separator_normalized_key": norm_slashes(expected) == norm_slashes(actual),
        "same_source_basename": norm_slashes(expected).rsplit("/", 1)[-1] ==
                                norm_slashes(actual).rsplit("/", 1)[-1],
    }

def synthetic_tests():
    name = "/src/files/C:\\checkout\\F.cs"
    assert classify(name, name)["exact_key"]
    assert not classify(name, name.upper())["exact_key"]
    assert classify(name, name.upper())["case_insensitive_key"]
    assert classify(name, "/src/files/C:/checkout/F.cs")["separator_normalized_key"]
    assert not classify(name, "/src/files/_/F.cs")["separator_normalized_key"]
    assert classify(name, "/src/files/_/F.cs")["same_source_basename"]
    assert not classify(name, "/src/files/_/Other.cs")["same_source_basename"]
    payload = (b"\x00"*48 + GUID_SHA256.bytes_le + struct.pack("<ii", 32, 0)
               + hashlib.sha256(b"fixture").digest())
    assert stream_record(payload)["digest"] == hashlib.sha256(b"fixture").digest()
    assert stream_record(payload[:-1]) is None
    assert stream_record(payload[:64] + struct.pack("<ii", 200, 0) + payload[72:]) is None
    assert stream_record(b"") is None
    print("EXP-038 synthetic key-equality and structured checksum positive/negative controls PASS")

def inspect(dll, pdb, physical_sources, url_dir, label):
    streams = read_msf(pdb.read_bytes())
    guid, age, names = parse_named_streams(streams[1], len(streams))
    if (guid, age) != read_pe_codeview(dll.read_bytes()):
        raise ValueError("Native PDB and DLL identity mismatch")
    native = {}
    for key, stream_id in names.items():
        if not key.casefold().startswith("/src/files/"):
            continue
        record = stream_record(streams[stream_id])
        if record is not None:
            native[key] = record
    reports = {}
    reader_urls = {}
    for reader in ("DNLIB", "CECIL"):
        path = url_dir / (label + "-" + reader + ".private")
        reader_urls[reader] = private_urls(path)
    for src in physical_sources:
        if not src.is_file():
            raise ValueError("Required physical owned source missing")
        physical = src.read_bytes()
        if not physical:
            raise ValueError("Empty source not valid")
        matching = [(key, record) for key, record in native.items()
                    if hashlib.new(record["algorithm"], physical).digest() == record["digest"]]
        if len(matching) != 1:
            raise ValueError("Owned source has not exactly one structured native digest record")
        key, record = matching[0]
        measured = {"structured_digest_physical_match": True,
                    "digest_algorithm": record["algorithm"],
                    "native_source_stream_present": True,
                    "reader_classifications": {}}
        for reader in ("DNLIB", "CECIL"):
            actual_url = reader_urls[reader].get(src.name)
            if actual_url is None:
                raise ValueError("Expected owned managed document absent")
            # Pinned dnlib: $"/src/files/{name}" case-insensitive dictionary.
            # Pinned Cecil/CCI: "/SRC/FILES/" + name.ToUpperInvariant() (case-agnostic for report).
            lookup = "/src/files/" + actual_url
            status = classify(lookup, key)
            status["pinned_reader_lookup_key_present_casefold"] = any(
                k.casefold() == lookup.casefold() for k in names
            )
            measured["reader_classifications"][reader] = status
        reports[src.name] = measured
    for source in physical_sources:
        for reader in ("DNLIB", "CECIL"):
            if source.name not in reader_urls[reader]:
                raise ValueError("Missing source in reader inventory")
    return {"native_pdb_pe_identity": "MATCHED",
            "structured_owned_document_digest_count": len(reports),
            "total_native_source_streams": sum(
                k.casefold().startswith("/src/files/") for k in names
            ),
            "owned": reports}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--fixture-root", type=Path)
    parser.add_argument("--application-root", type=Path)
    parser.add_argument("--private-url-dir", type=Path)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    if args.self_test:
        synthetic_tests()
        return
    if any(x is None for x in (args.fixture_root, args.application_root,
                                args.private_url_dir, args.output)):
        parser.error("Fixture root, application root, private URL dir and output required")
    if args.output.exists():
        parser.error("Refuse overwrite of final evidence")
    base = args.fixture_root
    source = base / "EXP037-source" / "DifferentialSource.cs"
    result = {}
    for label in VARIANTS:
        folder = base / ("EXP037-" + label)
        result[label] = inspect(folder / "Differential.dll",
                                folder / "Differential.pdb", [source],
                                args.private_url_dir, label)
    csv = args.application_root / "src" / "RecordSift.Infrastructure.Csv"
    result["frozen_csv_candidate"] = inspect(
        csv / "bin/Release/RecordSift.Infrastructure.Csv.dll",
        csv / "bin/Release/RecordSift.Infrastructure.Csv.pdb",
        [csv / f for f in OWNED], args.private_url_dir, "frozen_csv_candidate"
    )
    report = {
        "experiment": "EXP-038",
        "status": "STRUCTURAL_AND_KEY_ASSOCIATION_DIAGNOSTIC_ONLY",
        "scope": "Five fixed fixture variants plus four frozen CSV owned source files",
        "cases": result,
        "not_established": [
            "Debugger stepping, Visual Studio Package Manager installation",
            "Any missing/unclassified managed document authenticity",
            "Unsafe/untrusted PDB parsing",
            "Full compiler server or native writer equivalence",
            "Production Source Link acceptance",
        ],
        "privacy": "Only Booleans, bounded counts, allowed source basenames and checksum algorithm labels",
    }
    args.output.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    for case, row in result.items():
        for source_name, v in row["owned"].items():
            print("EXP038", case, source_name, "native-structured-digest=physical-match",
                  "DNLIB", v["reader_classifications"]["DNLIB"],
                  "CECIL", v["reader_classifications"]["CECIL"])
    print("EXP-038 structured native checksum + document/stream lookup report completed; no gate auto-approval")

if __name__ == "__main__":
    main()
